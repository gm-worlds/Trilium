let added = false;

export function addTfReachTranslations() {
    if (added) {
        return;
    }
    added = true;
    i18next.addResourceBundle("en", "translation", { tf: { reach: TF_REACH_EN } }, true, false);
    i18next.addResourceBundle("nl", "translation", { tf: { reach: TF_REACH_NL } }, true, false);
}
