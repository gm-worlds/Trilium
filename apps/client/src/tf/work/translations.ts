let added = false;

export function addTfWorkTranslations() {
    if (added) {
        return;
    }
    added = true;
    i18next.addResourceBundle("en", "translation", { tf: { work: TF_WORK_STRINGS_EN } }, true, false);
    i18next.addResourceBundle("nl", "translation", { tf: { work: TF_WORK_STRINGS_NL } }, true, false);
}
