let added = false;

export function addTeamTranslations() {
    if (added) {
        return;
    }
    added = true;
    i18next.addResourceBundle("en", "translation", { tf: { team: TEAM_STRINGS_EN } }, true, false);
    i18next.addResourceBundle("nl", "translation", { tf: { team: TEAM_STRINGS_NL } }, true, false);
}
